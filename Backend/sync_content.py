#!/usr/bin/env python3
"""Regenerate trusted gateway character / story canon from iOS bundled content.

Usage: python3 Backend/sync_content.py (run from any working directory).
No credentials are read or written by this script.
"""
from pathlib import Path
import json

root = Path(__file__).resolve().parents[1]
source = root / 'Tideverse' / 'Resources' / 'Stories'
characters = json.loads((source / 'characters.json').read_text(encoding='utf-8'))
stories = json.loads((source / 'stories.json').read_text(encoding='utf-8'))

meta = {}
for c in characters:
    meta[c['id']] = {k: c[k] for k in ('name', 'age', 'profession', 'biography', 'personality', 'voice', 'goal', 'boundary', 'openingLine')}
canon = {}
for s in stories:
    canon[s['characterID']] = {
        'title': s['title'],
        'premise': s['premise'],
        'chapters': [
            {
                'id': ch['id'],
                'title': ch['title'],
                'choices': {opt['id']: {'label': opt['label'], 'outcome': opt['outcome']} for opt in ch['choices']},
            } for ch in s['chapters']
        ]
    }
assert len(meta) == len(canon) == len(characters) and set(meta) == set(canon)
for name, var, body in (
    ('characters.js', 'CHARACTERS', meta),
    ('storyCanon.js', 'STORY_CANON', canon),
):
    target = root / 'Backend' / name
    target.write_text('// Auto-generated by Backend/sync_content.py from the bundled story JSON.\n'
                      f'export const {var} = '
                      + json.dumps(body, ensure_ascii=False, indent=2)
                      + ';\n', encoding='utf-8')
    print('Regenerated', target.name)
